- **นิ้ว 1** กดสาย 6 ที่เฟรตของโน้ตราก
- **นิ้ว 3** กดสาย 5 สูงขึ้นไป 2 เฟรต (ขั้นที่ 5)
- **นิ้ว 4** กดสาย 4 เฟรตเดียวกับนิ้ว 3 (ราก ตัวบน)
- ดีดแค่ 3 สายนี้ สายอื่นอุดเสียงไว้

ตัวอย่าง: **G5** = 3 5 5 x x x (ราก G อยู่สาย 6 เฟรต 3) **A5** = 5 7 7 x x x

## รูปบนสาย 5

รูปมือเดียวกัน ย้ายลงมาหนึ่งสาย รากอยู่สาย 5

- **C5** = x 3 5 5 x x (ราก C อยู่สาย 5 เฟรต 3)
- **D5** = x 5 7 7 x x

ใช้ชื่อโน้ตบนสาย 6 และสาย 5 จากบทตัวโน้ต 12 ตัว หาตำแหน่งพาวเวอร์คอร์ดใดก็ได้

## การอุดเสียงด้วยฝ่ามือ (Palm mute)

1. วางสันมือขวา (ด้านนิ้วก้อย) แตะสายเบา ๆ **ชิดสะพานสาย (Bridge)**
