# คอร์ดเปิดยอดฮิตและการเปลี่ยนคอร์ด

## คอร์ดเปิดคืออะไร

คอร์ดเปิด (Open chord) คือคอร์ดที่มีสายเปล่าปนอยู่ ใกล้หัวกีตาร์ เล่นง่ายและเสียงก้อง เป็นพื้นฐานของเพลงส่วนใหญ่

## คอร์ดที่ต้องรู้

- **G** — นิ้ว 2 สาย 6 เฟร็ต 3, นิ้ว 1 สาย 5 เฟร็ต 2, นิ้ว 3 สาย 1 เฟร็ต 3 ดีดครบ 6 สาย
- **C** — ดีดสาย 5 ถึง 1
- **D** — ดีดสาย 4 ถึง 1
- **Em** — ดีดครบ 6 สาย

คอร์ด G, C, D และ Em ใช้ร่วมกันได้ในเพลงป๊อปจำนวนมาก เช่นลำดับ G - Em - C - D

## เทคนิคการเปลี่ยนคอร์ด

1. ฝึกช้าๆ ก่อน ความถูกต้องสำคัญกว่าความเร็ว
2. มองล่วงหน้าว่านิ้วไหนอยู่ที่เดิมได้ (นิ้วหลัก) แล้วเลื่อนเฉพาะนิ้วที่ต้องย้าย
3. ยกนิ้วทั้งหมดพร้อมกันและวางพร้อมกัน ไม่วางทีละนิ้ว
4. ใช้เมโทรนอมตั้งไว้ช้าๆ แล้วเปลี่ยนคอร์ดทุก 4 จังหวะ ค่อยๆ เพิ่มความเร็ว

