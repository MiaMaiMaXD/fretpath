  insert into public.quiz_questions (id, lesson_id, prompt, sort_order)
  values (v_q, v_lesson, p_prompt, p_n);
  for i in 1..array_length(p_choices, 1) loop
    v_c := gen_random_uuid();
    insert into public.quiz_choices (id, question_id, text, sort_order)
