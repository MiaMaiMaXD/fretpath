## จังหวะ 4/4 คืออะไร

ตัวเลข 4/4 หมายถึง หนึ่งห้องมี 4 จังหวะ และโน้ตตัวดำเท่ากับหนึ่งจังหวะ เพลงป๊อปและร็อกส่วนใหญ่ใช้จังหวะนี้

