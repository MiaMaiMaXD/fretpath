# รู้จักส่วนประกอบของกีตาร์และการตั้งสาย

## ส่วนประกอบหลัก

กีตาร์โปร่งแบ่งเป็นสามส่วนใหญ่ๆ ได้แก่ หัวกีตาร์ (Headstock) คอกีตาร์ (Neck) และตัวกีตาร์ (Body)

- **หัวกีตาร์** มีลูกบิด (Tuning pegs) ใช้ไขสายให้ตึงหรือหย่อน
- **คอกีตาร์** มีเฟร็ต (Fret) เป็นแถบโลหะแบ่งช่อง และฟิงเกอร์บอร์ด (Fingerboard) ที่เรากดสาย
- **ตัวกีตาร์** มีซาวด์โฮล (Sound hole) ที่ช่วยให้เสียงก้อง และบริดจ์ (Bridge) ที่ยึดสายไว้

## สายและการนับ

กีตาร์มี 6 สาย นับจากสาย 1 (เส้นเล็กสุด เสียงสูงสุด) ไปถึงสาย 6 (เส้นใหญ่สุด เสียงต่ำสุด)

การตั้งสายมาตรฐาน (Standard tuning) จากสาย 6 ไปสาย 1 คือ **E A D G B E**

เคล็ดลับจำง่ายๆ ในภาษาอังกฤษ: *Eddie Ate Dynamite, Good Bye Eddie*

