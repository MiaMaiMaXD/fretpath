## ทำไม F ถึงยาก

คอร์ด F แบบเต็มเป็นคอร์ดทาบ (Barre chord) ที่นิ้วชี้ต้องกดหลายสายพร้อมกันที่เฟร็ต 1 ทำให้ต้องใช้แรงและเทคนิค ผู้เริ่มต้นหลายคนติดตรงนี้ ไม่ต้องกังวลเพราะมีวิธีง่ายกว่า

## F แบบง่าย

เล่นเฉพาะสาย 4 ถึง 1:

- นิ้ว 1 กดสาย 2 และสาย 1 พร้อมกันที่เฟร็ต 1 (ทาบเฉพาะสองสายบาง)
- นิ้ว 2 สาย 3 เฟร็ต 2
- นิ้ว 3 สาย 4 เฟร็ต 3

