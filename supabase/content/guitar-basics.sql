- ดีดลง (Down) คือดีดจากสายหนาไปสายบาง ตรงกับเลขจังหวะ
- ดีดขึ้น (Up) คือดีดจากสายบางไปสายหนา ตรงกับคำว่า "และ"

เมื่อนับแบบละเอียด: **1 และ 2 และ 3 และ 4 และ**

## รูปแบบเริ่มต้น

1. ดีดลงทุกจังหวะ: ↓ ↓ ↓ ↓
2. ดีดลงขึ้นสลับ: ↓↑ ↓↑ ↓↑ ↓↑
3. รูปแบบยอดนิยม: ↓ ↓↑ ↑↓↑ (ข้ามบางครั้งแต่ข้อมือยังแกว่งต่อเนื่อง)

